"""Phase 1 mock run: the full chain on real notices and profiles with MOCK AI outputs (SPEC §18).

    python3 pipeline/run_mock.py [--run-id mock-2026-11-05]

Writes /outputs/{run_id}/ (frozen JSON + manifest) and /outputs/{run_id}/mode_coverage.json. Fails (exit 1) if any
mode in SPEC §18 mode_coverage has no example. Never calls an AI model.
"""
from __future__ import annotations

import argparse
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from kvia import chain, coverage, manifest, tests_eval  # noqa: E402
from kvia.util import ROOT, load_config, read_json, sha256_file, write_json  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-id", default="mock-2026-11-05")
    args = ap.parse_args()
    cfg = load_config()
    run_id = args.run_id
    out = ROOT / "outputs" / run_id
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    decisions = {d["notice_id"]: d for d in read_json(ROOT / cfg["adviser_decisions"])["decisions"]}
    manual = read_json(ROOT / cfg["recorded_manual_additions"])["additions"]
    flags = read_json(ROOT / cfg["firm_flags"])["flags"]
    profiles = chain.load_profiles(cfg)

    store, act = chain.step_ingest(cfg)
    layouts = chain.generate_placeholders(cfg, store, act)
    pre = chain.step_preprocess(cfg, store, act, layouts, decisions)

    write_json(out / "00_ingest" / "notice_store.json", store)
    write_json(out / "0b_activeness.json", act)
    for nid, r in pre["retrieval"].items():
        write_json(out / "1a_retrieval" / f"{nid}.json", r)
    for nid, e in pre["extraction"].items():
        write_json(out / "1b_extraction" / f"{nid}.json", e)
    write_json(out / "1c_release_gate.json", {"gate": pre["gate"], "effective_requirements": pre["effective"],
                                              "adviser_decisions_file": cfg["adviser_decisions"]})

    screening, reports, health = {}, {}, {}
    for pid, prof in profiles.items():
        screening[pid] = chain.step_screen(cfg, store, pre, prof)
        reports[pid] = chain.step_report(cfg, store, pre, screening[pid], prof, manual)
        health[pid] = chain.step_health(cfg, prof)
        write_json(out / "2_screening" / f"{pid}.json", screening[pid])
        write_json(out / "3_reports" / f"{pid}.json", reports[pid])
        write_json(out / "s3_health_check" / f"{pid}.json", health[pid])

    inputs = [cfg["notice_export"], cfg["mock_notices"], cfg["adviser_decisions"], cfg["recorded_manual_additions"],
              cfg["firm_flags"], "pipeline/config.yaml"] + [f"{cfg['profiles_dir']}/{p}.json" for p in profiles]
    run_info = {
        "run_id": run_id, "mock": True, "phase": 1,
        "created_utc": datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
        "reference_datetime": cfg["reference_datetime"], "snapshot_date": cfg["snapshot_date"],
        "model": {"specified_in_docs": cfg["model"]["specified"], "used": cfg["model"]["phase_1"]},
        "prompt_versions": cfg["prompt_versions"],
        "weights": cfg["screening"]["weights"], "threshold": cfg["screening"]["threshold"],
        "readiness": cfg["readiness"], "health_check": cfg["health_check"],
        "steps_run": ["0 ingest", "0b activeness", "1a retrieval", "1b extraction (MOCK)", "1c release gate",
                      "adviser decisions (MOCK)", "2a screening (MOCK)", "2b ranking", "3a matching + classification (MOCK)",
                      "3b readiness", "3c indication", "S3 health check"],
        "input_checksums": {p: sha256_file(ROOT / p) for p in inputs},
        "profiles": list(profiles),
        "firm_flags": flags,
        "manual_additions_recorded": manual,
        "assumptions": [
            "Screening weights and threshold 60 (team-accepted starting values, SPEC §6)",
            "Tax certificate valid six months from issue unless the tender states otherwise (SPEC §7)",
            "Expiring-soon window 30 days after the deadline (SPEC §7)",
            "Health-check expiring window 60 days (agent default, Phase 1)",
            "Success targets in SPEC §12 are team assumptions",
        ],
        "notice": "MOCK DATA — tender documents not yet processed. Requirements, sub-scores and classifications are "
                  "generated by code from templates and describe no real tender.",
    }
    write_json(out / "run_info.json", run_info)
    cov = coverage.build(store, act, pre, screening, reports, health, flags, manual, decisions)
    write_json(out / "mode_coverage.json", cov)
    tests = tests_eval.evaluate(store, act, pre, screening, reports)
    write_json(out / "tests.json", tests)
    man = manifest.write(out, run_id)
    print(f"run {run_id}: {len(store['records'])} notices, {sum(a['active'] for a in act.values())} active, "
          f"{len(chain.released_ids(pre))} released; manifest {man['manifest_sha256'][:12]}")
    missing = [m for m in cov["modes"] if not m["examples"]]
    for m in cov["modes"]:
        print(f"  [{'x' if m['examples'] else ' '}] {m['group']}: {m['mode']}  ({len(m['examples'])})")
    if missing:
        print(f"MODE COVERAGE FAILED: {len(missing)} modes without example", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

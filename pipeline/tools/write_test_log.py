"""Write /test_log.md in the assignment's Appendix A format from a run's tests.json and data/test_log_notes.json.

    python3 pipeline/tools/write_test_log.py [run_id]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TYPE = {"typical": "Typical", "edge": "Edge / difficult", "failure": "Edge / failure", "key_assumption": "Key assumption",
        "recompute": "Recompute", "stability": "Stability"}


def cell(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def main() -> int:
    cfg = json.loads((ROOT / "config/website.json").read_text())
    run_id = sys.argv[1] if len(sys.argv) > 1 else cfg["run_id"]
    tests = json.loads((ROOT / "outputs" / run_id / "tests.json").read_text())
    notes = json.loads((ROOT / "data/test_log_notes.json").read_text())["notes"]
    info = json.loads((ROOT / "outputs" / run_id / "run_info.json").read_text())
    lines = [
        "# Appendix A: Prototype Test Log",
        "",
        f"Run: `{run_id}`{' (MOCK — Phase 1)' if info.get('mock') else ''} · reference date {info['reference_datetime'][:10]}"
        f" · generated by `pipeline/tools/write_test_log.py` from `outputs/{run_id}/tests.json` and `data/test_log_notes.json`.",
        "",
    ]
    if info.get("mock"):
        lines += ["> **Phase 1 mock run.** “passed (mock)” shows only that the code paths behave as specified on mock",
                  "> content. It is NOT test evidence about real tenders and must not be reported as a test result.",
                  "> Replace this log with the Phase 2 results.", ""]
    lines += ["| # | Case type | Scenario / input | Expected outcome | Observed result | Learning / revision |",
              "|---|---|---|---|---|---|"]
    for i, t in enumerate(tests, 1):
        lines.append(f"| {i} | {TYPE.get(t['type'], t['type'])} | {cell(t['id'] + ': ' + t['scenario'])} | {cell(t['expected'])} | "
                     f"{cell('[' + t['status'] + '] ' + t['observed_en'])} | {cell(notes.get(t['id'], {}).get('en', ''))} |")
    (ROOT / "test_log.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote test_log.md ({len(tests)} tests)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
